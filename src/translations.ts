export function translate(value: string): string {
  const t = value.trim();
  if (zh[t]) return value.replace(t, zh[t]);

  const arrowMatch = t.match(/^(.*?)\s*([↗↘↓←])$/);
  if (arrowMatch && zh[arrowMatch[1]]) {
    return `${zh[arrowMatch[1]]} ${arrowMatch[2]}`;
  }

  if (t.startsWith('← ') && zh[t]) return zh[t];

  if (t.startsWith('QR code scanned, but it does not match eSIM LPA format:')) {
    const tail = t.slice('QR code scanned, but it does not match eSIM LPA format:'.length).trim();
    return `${zh['QR code scanned, but it does not match eSIM LPA format:']} ${tail}`;
  }

  if (t.startsWith('Screen cutout capture failed:')) {
    const tail = t.slice('Screen cutout capture failed:'.length).trim();
    return `${zh['Screen cutout capture failed:']} ${tail}`;
  }

  return value
    .replace(/^Last checked:$/, '上次检查：')
    .replace(/^Auto-clean enabled at (\d+)% \(target (\d+)%\)$/, '达到 $1% 自动清理（目标降至 $2%）')
    .replace(/^Connected \(([^)]+) ping\)$/, '已连接（延迟 $1）')
    .replace(/^Local JSON store ready \(([^)]+) read\)$/, '本地 JSON 存储正常（读取 $1）')
    .replace(/^(\d+(?:\.\d+)?)% of (\d+) MiB limit$/, '已用 $1%（上限 $2 MiB）')
    .replace(/^(\d+(?:\.\d+)?)% of 30 MiB soft cap$/, '已用 $1%（本地参考上限 30 MiB）')
    .replace(/^(\d+) \/ (\d+) entries stored$/, '已存 $1 / $2 条记录')
    .replace(/^Redis connection error \(([^)]+)\)$/, 'Redis 连接出错（$1）')
    .replace(/^Auto-refresh: (\d+)s$/, '每 $1 秒自动刷新')
    .replace(/^Created ([A-Za-z0-9_-]+) \(link copied\)\.$/, '已生成 $1（链接已复制）')
    .replace(/^Standby link ready \(([^)]+)\)$/, '待激活链接已生成（$1）')
    .replace(/^Status for ([A-Za-z0-9_-]+)$/, '激活 $1 的状态')
    .replace(/^Edit activation ([A-Za-z0-9_-]+)$/, '编辑激活 $1')
    .replace(/^Delete activation ([A-Za-z0-9_-]+)$/, '删除激活 $1')
    .replace(/^Delete history ([A-Za-z0-9_-]+)$/, '删除历史 $1')
    .replace(/NEW \/ /g, '全新 / ')
    .replace(/^(\d+) months$/, '$1 个月')
    .replace(/^for (\d+) months$/, '共 $1 个月')
    .replace(/^That's (\$[\d.,]+) per month, paid upfront\.$/, '算下来每个月才 $1，一次付清省心。')
    .replace(/^From (\$[\d,]+) ↗$/, '$1 起 ↗')
    .replace(/, three-quarter view$/, '，侧面展示')
    .replace(/, front view$/, '，正面展示')
    .replace(/, back view$/, '，背面展示')
    .replace(/^Explore (iPhone.*), (.*), from every angle$/, '360° 看看 $1（$2）')
    .replace(
      /^(.*?): (.*?) per month, (\d+) months for (\$[\d.,]+) total\. Taxes and fees included\.$/,
      '$1：每月 $2，$3 个月一共 $4（全包无杂费）。'
    )
    .replace(
      /^(.*?): Unlimited data, (\d+) months for (\$[\d.,]+) total\. Taxes and fees included\.$/,
      '$1：无限流量，$2 个月一共 $3（全包无杂费）。'
    );
}
